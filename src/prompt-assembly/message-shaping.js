/**
 * Chat-completion message shaping (Phase 2.5.3).
 *
 * setOpenAIMessages and setOpenAIMessageExamples convert the stored chat into the
 * message array the completion endpoint receives. They lived in openai.js, which the
 * server cannot import, so the authoritative turn had no way to build its `messages`
 * input.
 *
 * Everything they read from the page arrives through an explicit context: the settings,
 * the resolved model, the ignore/narrator/name enums, the selected group, the name
 * overrides and the media helpers. Example parsing already lives in the shared macro
 * helpers, so it is imported directly.
 */

import { parseExampleIntoIndividual } from './macro-helpers.js';

export function setOpenAIMessages(chat, context = {}) {
    let j = 0;
    // clean openai msgs
    const messages = [];
    // Get current API and model for thought signature validation
    const currentApi = context.oaiSettings.chat_completion_source;
    const currentModel = context.getChatCompletionModel();

    for (let i = chat.length - 1; i >= 0; i--) {
        let role = chat[j].is_user ? 'user' : 'assistant';
        let content = chat[j].mes;

        // If this symbol flag is set, completely ignore the message.
        // This can be used to hide messages without affecting the number of messages in the chat.
        if (chat[j].extra?.[context.ignoreSymbol]) {
            j++;
            continue;
        }

        // 100% legal way to send a message as system
        if (chat[j].extra?.type === context.systemMessageTypes.NARRATOR) {
            role = 'system';
        }

        // for groups or sendas command - prepend a character's name
        switch (context.oaiSettings.names_behavior) {
            case context.characterNamesBehavior.NONE:
                break;
            case context.characterNamesBehavior.DEFAULT:
                if ((context.selectedGroup && chat[j].name !== context.name1) || (chat[j].force_avatar && chat[j].name !== context.name1 && chat[j].extra?.type !== context.systemMessageTypes.NARRATOR)) {
                    content = `${chat[j].name}: ${content}`;
                }
                break;
            case context.characterNamesBehavior.CONTENT:
                if (chat[j].extra?.type !== context.systemMessageTypes.NARRATOR) {
                    content = `${chat[j].name}: ${content}`;
                }
                break;
            case context.characterNamesBehavior.COMPLETION:
                break;
            default:
                break;
        }

        // remove caret return (waste of tokens)
        content = content.replace(/\r/gm, '');

        const name = chat[j].name;
        const media = chat[j]?.extra?.media;
        const mediaDisplay = context.getMediaDisplay(chat[j]);
        const mediaIndex = context.getMediaIndex(chat[j]);
        const invocations = chat[j]?.extra?.tool_invocations?.slice();

        // Only send thought signatures if they were generated by the same API and model
        const originApi = chat[j]?.extra?.api;
        const originModel = chat[j]?.extra?.model;
        const isSameModel = originApi === currentApi && originModel === currentModel;
        // In group chats, only include reasoning from the currently generating character
        const isOtherGroupMember = context.selectedGroup && chat[j].name !== context.name2;
        const signature = isSameModel && !isOtherGroupMember ? chat[j]?.extra?.reasoning_signature : null;
        const reasoning = isSameModel && !isOtherGroupMember ? String(chat[j]?.extra?.reasoning ?? '') : '';

        // Remove reasoning metadata from invocations if the API/model don't match
        if (Array.isArray(invocations) && invocations.length > 0) {
            invocations.forEach((invocation, index) => {
                if (!isSameModel && (invocation.signature || invocation.reasoning)) {
                    const cloneInvocation = structuredClone(invocation);
                    delete cloneInvocation.signature;
                    delete cloneInvocation.reasoning;
                    invocations[index] = cloneInvocation;
                }
            });
        }

        messages[i] = { 'role': role, 'content': content, name: name, 'media': media, 'mediaDisplay': mediaDisplay, 'mediaIndex': mediaIndex, 'invocations': invocations, 'signature': signature, 'reasoning': reasoning };
        j++;
    }

    return messages;
}

export function setOpenAIMessageExamples(mesExamplesArray, context = {}) {
    // get a nice array of all blocks of all example messages = array of arrays (important!)
    const examples = [];
    for (let item of mesExamplesArray) {
        // remove <START> {Example Dialogue:} and replace \r\n with just \n
        let replaced = item.replace(/<START>/i, '{Example Dialogue:}').replace(/\r/gm, '');
        let parsed = parseExampleIntoIndividual(replaced, true, context);
        // add to the example message blocks array
        examples.push(parsed);
    }
    return examples;
}
